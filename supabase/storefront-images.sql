-- Run once in Supabase Dashboard > SQL Editor as postgres.
-- Stores homepage image metadata and creates the public image bucket.

create table if not exists public.storefront_images (
  id bigint generated by default as identity primary key,
  slot text not null check (slot in ('hero', 'side_one', 'side_two')),
  storage_path text unique,
  image_url text,
  alt_text text not null default '',
  position integer not null default 1 check (position > 0),
  created_at timestamptz not null default now(),
  constraint storefront_images_one_source check (
    (storage_path is not null and image_url is null)
    or (storage_path is null and image_url is not null and image_url ~* '^https?://')
  )
);

-- Make this migration safe to re-run when the upload-only table already exists.
alter table public.storefront_images alter column storage_path drop not null;
alter table public.storefront_images add column if not exists image_url text;
do $$
begin
  if not exists (
    select 1 from pg_constraint
    where conrelid = 'public.storefront_images'::regclass
      and conname = 'storefront_images_one_source'
  ) then
    alter table public.storefront_images
      add constraint storefront_images_one_source check (
        (storage_path is not null and image_url is null)
        or (storage_path is null and image_url is not null and image_url ~* '^https?://')
      );
  end if;
end;
$$;

create unique index if not exists storefront_images_one_per_fixed_slot
  on public.storefront_images (slot)
  where slot in ('side_one', 'side_two');

alter table public.storefront_images enable row level security;
grant select on public.storefront_images to anon, authenticated;
grant insert, update, delete on public.storefront_images to authenticated;

drop policy if exists "Anyone can view storefront image records" on public.storefront_images;
create policy "Anyone can view storefront image records"
  on public.storefront_images for select to anon, authenticated using (true);

drop policy if exists "Admins manage storefront image records" on public.storefront_images;
create policy "Admins manage storefront image records"
  on public.storefront_images for all to authenticated
  using ((auth.jwt() -> 'app_metadata' ->> 'role') = 'admin')
  with check ((auth.jwt() -> 'app_metadata' ->> 'role') = 'admin');

insert into storage.buckets (id, name, public, file_size_limit, allowed_mime_types)
values (
  'storefront-images',
  'storefront-images',
  true,
  10485760,
  array['image/jpeg', 'image/png', 'image/webp', 'image/gif', 'image/avif']::text[]
)
on conflict (id) do update
set public = excluded.public,
    file_size_limit = excluded.file_size_limit,
    allowed_mime_types = excluded.allowed_mime_types;

drop policy if exists "Admins upload storefront images" on storage.objects;
create policy "Admins upload storefront images"
  on storage.objects for insert to authenticated
  with check (
    bucket_id = 'storefront-images'
    and (auth.jwt() -> 'app_metadata' ->> 'role') = 'admin'
  );

drop policy if exists "Admins update storefront images" on storage.objects;
create policy "Admins update storefront images"
  on storage.objects for update to authenticated
  using (
    bucket_id = 'storefront-images'
    and (auth.jwt() -> 'app_metadata' ->> 'role') = 'admin'
  )
  with check (
    bucket_id = 'storefront-images'
    and (auth.jwt() -> 'app_metadata' ->> 'role') = 'admin'
  );

drop policy if exists "Admins delete storefront images" on storage.objects;
create policy "Admins delete storefront images"
  on storage.objects for delete to authenticated
  using (
    bucket_id = 'storefront-images'
    and (auth.jwt() -> 'app_metadata' ->> 'role') = 'admin'
  );

create or replace function public.reorder_storefront_hero(item_ids bigint[])
returns void
language plpgsql
security invoker
set search_path = public
as $$
declare
  current_count integer;
begin
  if (auth.jwt() -> 'app_metadata' ->> 'role') is distinct from 'admin' then
    raise exception 'Administrator access required.' using errcode = '42501';
  end if;

  select count(*) into current_count
  from public.storefront_images
  where slot = 'hero';

  if cardinality(item_ids) <> current_count
     or (select count(distinct id) from unnest(item_ids) as ids(id)) <> current_count
     or exists (
       select 1 from unnest(item_ids) as ids(id)
       where not exists (
         select 1 from public.storefront_images image
         where image.id = ids.id and image.slot = 'hero'
       )
     ) then
    raise exception 'Provide each carousel image exactly once.' using errcode = '22023';
  end if;

  update public.storefront_images as image
  set position = ids.ordinality::integer
  from unnest(item_ids) with ordinality as ids(id, ordinality)
  where image.id = ids.id and image.slot = 'hero';
end;
$$;

grant execute on function public.reorder_storefront_hero(bigint[]) to authenticated;
