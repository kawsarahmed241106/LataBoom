-- Run in Supabase Dashboard > SQL Editor as postgres.
-- Products are public to browse; only admins can add, update, or remove them.

create table if not exists public.products (
  id bigint generated by default as identity primary key,
  image_url text not null check (image_url ~* '^https?://'),
  images text[] not null default '{}',
  name text not null check (char_length(trim(name)) between 1 and 180),
  category text,
  short_description text not null default '',
  description text not null default '',
  price numeric(12, 2) not null check (price > 0),
  regular_price numeric(12, 2),
  special_price numeric(12, 2),
  quantity_prices jsonb not null default '[]'::jsonb,
  is_on_sale boolean not null default false,
  in_stock boolean not null default true,
  sales_count integer not null default 0,
  view_count integer not null default 0,
  created_at timestamptz not null default now()
);

-- Migrate existing catalog entries while retaining their current images and prices.
alter table public.products add column if not exists images text[] not null default '{}';
alter table public.products add column if not exists category text;
alter table public.products add column if not exists short_description text not null default '';
alter table public.products add column if not exists regular_price numeric(12, 2);
alter table public.products add column if not exists special_price numeric(12, 2);
alter table public.products add column if not exists quantity_prices jsonb not null default '[]'::jsonb;
alter table public.products add column if not exists sales_count integer not null default 0;
alter table public.products add column if not exists view_count integer not null default 0;

update public.products
set images = case when cardinality(images) = 0 then array[image_url] else images end,
    regular_price = coalesce(regular_price, price),
    short_description = case when short_description = '' then left(description, 300) else short_description end
where cardinality(images) = 0 or regular_price is null;

alter table public.products alter column regular_price set not null;
alter table public.products drop constraint if exists products_description_check;
alter table public.products drop constraint if exists products_short_description_check;
alter table public.products drop constraint if exists products_images_check;
alter table public.products drop constraint if exists products_category_check;
alter table public.products drop constraint if exists products_regular_price_check;
alter table public.products drop constraint if exists products_special_price_check;
alter table public.products drop constraint if exists products_quantity_prices_check;
alter table public.products drop constraint if exists products_sales_count_check;
alter table public.products drop constraint if exists products_view_count_check;
alter table public.products
  add constraint products_description_check check (char_length(description) <= 10000);
alter table public.products
  add constraint products_short_description_check check (char_length(short_description) <= 300);
alter table public.products
  add constraint products_images_check check (cardinality(images) >= 1);
alter table public.products
  add constraint products_category_check check (category is null or category in ('honey', 'dry_food', 'mix_food', 'nuts_seeds', 'pickle', 'dates', 'masala', 'tea'));
alter table public.products
  add constraint products_regular_price_check check (regular_price > 0);
alter table public.products
  add constraint products_special_price_check check (special_price is null or (special_price > 0 and special_price < regular_price));
alter table public.products
  add constraint products_quantity_prices_check check (jsonb_typeof(quantity_prices) = 'array');
alter table public.products
  add constraint products_sales_count_check check (sales_count >= 0);
alter table public.products
  add constraint products_view_count_check check (view_count >= 0);

alter table public.products enable row level security;
grant select on public.products to anon, authenticated;
grant insert, update, delete on public.products to authenticated;
grant usage, select on sequence public.products_id_seq to authenticated;

drop policy if exists "Anyone can read products" on public.products;
create policy "Anyone can read products"
  on public.products for select to anon, authenticated using (true);

drop policy if exists "Admins manage products" on public.products;
create policy "Admins manage products"
  on public.products for all to authenticated
  using ((auth.jwt() -> 'app_metadata' ->> 'role') = 'admin')
  with check ((auth.jwt() -> 'app_metadata' ->> 'role') = 'admin');

create or replace function public.record_product_view(target_product_id bigint)
returns void
language sql
security definer
set search_path = public, pg_temp
as $$
  update public.products
  set view_count = view_count + 1
  where id = target_product_id;
$$;

revoke all on function public.record_product_view(bigint) from public;
grant execute on function public.record_product_view(bigint) to anon, authenticated;
