-- Run once in Supabase Dashboard > SQL Editor as postgres.
-- One Big post is allowed; Small posts have no count limit. Public visitors can read; only admins can write.

create table if not exists public.blog_posts (
  id bigint generated by default as identity primary key,
  image_url text not null check (image_url ~* '^https?://'),
  title text not null check (char_length(trim(title)) between 1 and 200),
  description text not null default '',
  post_type text not null default 'small',
  created_at timestamptz not null default now()
);

-- Migrate earlier blog tables in place; existing posts become Small posts.
alter table public.blog_posts add column if not exists post_type text not null default 'small';
alter table public.blog_posts alter column description set default '';
alter table public.blog_posts drop constraint if exists blog_posts_description_check;
alter table public.blog_posts drop constraint if exists blog_posts_content_check;
alter table public.blog_posts drop constraint if exists blog_posts_post_type_check;
alter table public.blog_posts
  add constraint blog_posts_post_type_check check (post_type in ('big', 'small'));
alter table public.blog_posts
  add constraint blog_posts_content_check check (
    (post_type = 'big' and char_length(trim(description)) between 1 and 5000)
    or (post_type = 'small' and char_length(trim(description)) between 0 and 5000)
  );
create unique index if not exists blog_posts_one_big_post
  on public.blog_posts (post_type) where post_type = 'big';

alter table public.blog_posts enable row level security;
grant select on public.blog_posts to anon, authenticated;
grant insert, update, delete on public.blog_posts to authenticated;

drop policy if exists "Anyone can read blog posts" on public.blog_posts;
create policy "Anyone can read blog posts"
  on public.blog_posts for select to anon, authenticated using (true);

drop policy if exists "Admins manage blog posts" on public.blog_posts;
create policy "Admins manage blog posts"
  on public.blog_posts for all to authenticated
  using ((auth.jwt() -> 'app_metadata' ->> 'role') = 'admin')
  with check ((auth.jwt() -> 'app_metadata' ->> 'role') = 'admin');
